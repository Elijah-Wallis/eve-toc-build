def _json(data: object) -> str:
    return json.dumps(data, indent=2, sort_keys=False)


def _yaml(data: object) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=False)


def _ontology_extension(spec: MedspaClientSpec, result: PlatformGenerationResult | None = None) -> str:
    optimization = result.optimization if result else run_platform_optimization(spec)
    payload = {
        "version": "0.1.0",
        "platform_layer": "EVE_L5_Medspa_IaC",
        "client": spec.to_dict(),
        "routing": optimization.triage.to_dict(),
        "entities": {
            "service_nodes": [
                {
                    "id": f"service:{spec.slug}:{service.name.lower().replace(' ', '_')}",
                    "name": service.name,
                    "category": service.category,
                    "avg_ticket": service.avg_ticket,
                    "compliance_tags": service.compliance_tags,
                }
                for service in spec.services
            ],
            "persona_nodes": [
                {
                    "id": f"persona:{spec.slug}:{persona.name.lower().replace(' ', '_')}",
                    "name": persona.name,
                    "channels": persona.channels,
                    "concerns": persona.concerns,
                }
                for persona in spec.personas
            ],
            "location_nodes": [
                {
                    "id": f"location:{spec.slug}:{location.city.lower()}",
                    "city": location.city,
                    "state": location.state,
                    "timezone": location.timezone,
                }
                for location in spec.locations
            ],
        },
    }
    return _json(payload)


