def _supabase_sql(spec: MedspaClientSpec, result: PlatformGenerationResult) -> str:
    schema_name = f"l5_{spec.slug}"
    services_insert = "\n".join(
        [
            "insert into "
            + schema_name
            + ".service_catalog (service_name, category, avg_ticket, duration_minutes, compliance_tags)"
            + f"\nvalues ('{service.name}', '{service.category}', {service.avg_ticket:.2f}, {service.duration_minutes}, '{json.dumps(service.compliance_tags)}');"
            for service in spec.services
        ]
    )
    return f"""-- Generated by EVE L5_Medspa_IaC prototype
create schema if not exists {schema_name};

create table if not exists {schema_name}.client_profile (
    client_id text primary key,
    medspa_name text not null,
    primary_city text not null,
    branding jsonb not null,
    governance jsonb not null,
    thermo_triage jsonb not null,
    created_at timestamptz not null default timezone('utc', now())
);

create table if not exists {schema_name}.service_catalog (
    id bigserial primary key,
    service_name text not null,
    category text not null,
    avg_ticket numeric not null,
    duration_minutes integer not null,
    compliance_tags jsonb not null default '[]'::jsonb
);

create table if not exists {schema_name}.persona_matrix (
    id bigserial primary key,
    persona_name text not null,
    channels jsonb not null,
    concerns jsonb not null,
    urgency_bias numeric not null
);

create table if not exists {schema_name}.journey_forecast (
    forecast_key text primary key,
    forecast_value numeric not null,
    explanation text not null
);

insert into {schema_name}.client_profile (
    client_id,
    medspa_name,
    primary_city,
    branding,
    governance,
    thermo_triage
) values (
    '{spec.client_id}',
    '{spec.medspa_name}',
    '{spec.primary_location.city}',
    '{json.dumps(spec.branding.to_dict())}'::jsonb,
    '{json.dumps(spec.governance.to_dict())}'::jsonb,
    '{json.dumps(result.optimization.triage.to_dict())}'::jsonb
)
on conflict (client_id) do update set
    medspa_name = excluded.medspa_name,
    primary_city = excluded.primary_city,
    branding = excluded.branding,
    governance = excluded.governance,
    thermo_triage = excluded.thermo_triage;

{services_insert}
"""


