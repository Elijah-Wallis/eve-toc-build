def _build_artifacts(spec: MedspaClientSpec, result: PlatformGenerationResult) -> List[GeneratedArtifact]:
    base = f"generated/{spec.slug}"
    return [
        GeneratedArtifact(f"{base}/ontology_extension.json", _ontology_extension(spec, result), "ontology"),
        GeneratedArtifact(f"{base}/ontology_shapes.ttl", _shacl_shapes(spec), "shacl"),
        GeneratedArtifact(f"{base}/supabase_extension.sql", _supabase_sql(spec, result), "sql"),
        GeneratedArtifact(f"{base}/retell_voice_agent.yaml", _voice_agent_yaml(spec, result), "voice"),
        GeneratedArtifact(f"{base}/n8n_workflow.json", _workflow_json(spec, result), "workflow"),
        GeneratedArtifact(f"{base}/telegram_orchestrator.yaml", _telegram_orchestrator_yaml(spec, result), "orchestrator"),
        GeneratedArtifact(f"{base}/digital_twin_simulator.json", _simulator_json(spec, result), "simulator"),
        GeneratedArtifact(f"{base}/governance_manifest.json", _governance_json(spec, result), "governance"),
        GeneratedArtifact(f"{base}/docker-compose.yml", _docker_compose(spec), "iac"),
        GeneratedArtifact(f"{base}/ecosystem.config.cjs", _pm2_ecosystem(spec), "iac"),
        GeneratedArtifact(f"{base}/launchd.plist", _launchd_plist(spec), "iac"),
        GeneratedArtifact(f"{base}/CLOUD_READY.md", _cloud_readme(spec, result), "doc"),
    ]


def generate_platform_bundle(source: str | dict) -> PlatformGenerationResult:
    spec = parse_client_spec(source)
    optimization = run_platform_optimization(spec)
    placeholder = PlatformGenerationResult(spec=spec, optimization=optimization, artifacts=[])
    artifacts = _build_artifacts(spec, placeholder)
    return PlatformGenerationResult(spec=spec, optimization=optimization, artifacts=artifacts)


def write_generation_result(result: PlatformGenerationResult, output_dir: str | Path) -> List[Path]:
    target_root = Path(output_dir)
    written: List[Path] = []
    for artifact in result.artifacts:
        path = target_root / artifact.path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(artifact.content, encoding="utf-8")
        written.append(path)
    manifest_path = target_root / f"generated/{result.spec.slug}/manifest.json"
    manifest_path.write_text(_json(result.to_dict()), encoding="utf-8")
    written.append(manifest_path)
    return written
