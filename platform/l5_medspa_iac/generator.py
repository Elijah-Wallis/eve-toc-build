            "@prefix eve: <https://eve.local/ontology/> .",
            "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
            "",
            f"eve:{spec.slug}_ServiceShape a sh:NodeShape ;",
            "  sh:targetClass eve:Service ;",
